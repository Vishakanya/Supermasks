    plt.title('Absolute Häufigkeiten\nincorrect responses')
    plt.xlabel('Response Label')
    plt.ylabel('Adversarial Label')

    # 2. Proportionen
    prop_table = count_table.div(count_table.sum(axis=1), axis=0)

    plt.subplot(1, 2, 2)
    sns.heatmap(prop_table, annot=True, fmt='.2f', cmap='Oranges')
    plt.title('Proportionen\nincorrect responses')
    plt.xlabel('Response Label')
    plt.ylabel('Adversarial Label')

    plt.tight_layout()
    plt.show()

    return prop_table

