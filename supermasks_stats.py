def prepare_gaussian_baseline(df):
    """Bereitet Gaussian baseline Daten vor"""
    df_gauss_incorrect = df[(df['mask_type'] == 'gaussian') & (df['correct'] == 0)].copy()

    # Häufigkeitsverteilung der responses in gaussian condition
    gaussian_responses = df_gauss_incorrect['response_label'].value_counts()
    gaussian_proportions = gaussian_responses / gaussian_responses.sum()

    print("="*60)
    print("GAUSSIAN BASELINE (incorrect trials)")
    print("="*60)
    print("Response distribution:")
    for label, count in gaussian_responses.items():
        prop = gaussian_proportions[label]
        print(f"{label}: {count} ({prop:.3f})")

    return gaussian_responses, gaussian_proportions

def compare_with_gaussian_baseline(df, count_table):
    """Vergleicht adversarial results mit gaussian baseline"""
    gaussian_responses, gaussian_proportions = prepare_gaussian_baseline(df)

    print("\n" + "="*60)
    print("VERGLEICH: ADVERSARIAL vs GAUSSIAN BASELINE")
    print("="*60)

    results = []

    for adv_cat in count_table.index:
        if adv_cat in count_table.columns:
            # Adversarial condition: Wie oft wurde die attack-category gewählt?
            adv_attack_count = count_table.loc[adv_cat, adv_cat]
            adv_total = count_table.loc[adv_cat].sum()
            adv_prop = adv_attack_count / adv_total

            # Gaussian baseline: Wie oft wurde diese category gewählt?
            gauss_count = gaussian_responses.get(adv_cat, 0)
            gauss_total = gaussian_responses.sum()
            gauss_prop = gauss_count / gauss_total

            print(f"\nCategory: {adv_cat}")
            print(f"Adversarial: {adv_attack_count}/{adv_total} = {adv_prop:.3f}")
            print(f"Gaussian:    {gauss_count}/{gauss_total} = {gauss_prop:.3f}")
            print(f"Difference:  {adv_prop - gauss_prop:.3f}")

            # 2x2 Chi²-Test für diese spezifische category
            contingency_2x2 = np.array([
                [adv_attack_count, adv_total - adv_attack_count],  # adversarial
                [gauss_count, gauss_total - gauss_count]           # gaussian
            ])

            chi2_stat, p_val, _, _ = chi2_contingency(contingency_2x2)

            print(f"Chi²-Test: χ² = {chi2_stat:.3f}, p = {p_val:.4f}")

            if p_val < 0.05:
                print(f"→ Significant difference!")
            else:
                print(f"→ no significant difference!")

            results.append({
                'category': adv_cat,
                'adv_count': adv_attack_count,
                'adv_total': adv_total,
                'adv_prop': adv_prop,
                'gauss_count': gauss_count,
                'gauss_total': gauss_total,
                'gauss_prop': gauss_prop,
                'difference': adv_prop - gauss_prop,
                'chi2': chi2_stat,
                'p_value': p_val,
                'significant': p_val < 0.05
            })

    return pd.DataFrame(results)

