def prepare_adversarial_data(df):
    """Bereitet die Daten für die adversarial mask Analyse vor"""
    # Filter for adversarial mask and incorrect trials
    df_adv_incorrect = df[(df['mask_type'] == 'adversarial') & (df['correct'] == 0)].copy()

    # Extract only the broad adversarial label (ignore numbers)
    df_adv_incorrect['adv_label_cat'] = df_adv_incorrect['adversarial_label'].str.extract(r'([A-Za-z]+)')

    return df_adv_incorrect

def create_cross_table(df_adv_incorrect):
    """Erstellt Kreuztabelle für adversarial labels vs responses"""
    count_table = pd.crosstab(
        df_adv_incorrect['adv_label_cat'],
        df_adv_incorrect['response_label']
    )
    return count_table

def plot_heatmaps(count_table):
    """Erstellt Heatmaps für absolute und relative Häufigkeiten"""
    # 1. Absolute Häufigkeiten
    plt.figure(figsize=(12, 5))

    plt.subplot(1, 2, 1)
