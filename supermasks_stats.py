from scipy.stats import wilcoxon

def simulate_power_wilcoxon(x, y, n_sim=10000, alpha=0.05, correction_factor=1):
    """Simulation-based power analysis for one-sided paired Wilcoxon test."""
    count_significant = 0
    n = len(x)

    for _ in range(n_sim):
       # generate paired samples with a small effect size (e.g., delta = +0.3)
        noise = np.random.normal(0, 1, n)
        noise = np.random.normal(0, 1, n)
        x_sim = x + noise
        y_sim = y + noise + 0.3  # introduce the simulated difference
        try:
            stat, p = wilcoxon(x_sim, y_sim, alternative='less')
            if p < (alpha / correction_factor):
                count_significant += 1
        except ValueError:
            continue  # # skip iterations that fail (e.g., too many ties)

    return count_significant / n_sim

