def create_contingency_for_chi2(count_table):
    """
    Erstellt Kontingenztafel für Chi²-Test:
    Für jede adversarial category: [correct attack response, other responses]
    """
    contingency_data = []
    categories = count_table.index

    for cat in categories:
        # Anzahl Antworten in der attack-Kategorie
        attack_responses = count_table.loc[cat, cat] if cat in count_table.columns else 0

        # Anzahl Antworten in anderen Kategorien
        other_responses = count_table.loc[cat].sum() - attack_responses

        contingency_data.append([attack_responses, other_responses])
        print(f"{cat}: {attack_responses} attack responses, {other_responses} other responses")

    return np.array(contingency_data), categories

def perform_chi2_independence_test(count_table):
    """Führt Chi²-Test auf Unabhängigkeit durch"""
    contingency_array, categories = create_contingency_for_chi2(count_table)

    print("="*60)
    print("CHI²-TEST AUF UNABHÄNGIGKEIT")
    print("="*60)
    print("H0: Die Wahrscheinlichkeit einer 'attack response' ist unabhängig von der adversarial category")
    print("H1: Es gibt systematische Unterschiede zwischen den categories")
    print()

    # Chi²-Test
    chi2_stat, p_val, dof, expected = chi2_contingency(contingency_array)

    print("Kontingenztafel:")
    print(f"{'Category':<12} {'Attack Resp.':<12} {'Other Resp.':<12} {'Total':<12}")
    print("-" * 50)
    for i, cat in enumerate(categories):
        total = contingency_array[i].sum()
        print(f"{cat:<12} {contingency_array[i][0]:<12} {contingency_array[i][1]:<12} {total:<12}")

    print(f"\nChi² = {chi2_stat:.3f}")
    print(f"df = {dof}")
    print(f"p-value = {p_val:.4f}")

    if p_val < 0.05:
        print(f"Ergebnis: Signifikant (p < 0.05) → H0 verwerfen")
        print("Die adversarial attacks scheinen zu funktionieren!")
    else:
        print(f"Ergebnis: Nicht signifikant (p ≥ 0.05) → H0 beibehalten")
        print("Kein Beweis für systematische adversarial effects")

    print("\nErwartete Häufigkeiten unter H0:")
    print(np.round(expected, 2))

    return chi2_stat, p_val, contingency_array

